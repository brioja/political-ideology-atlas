// People whose own books are being fetched (Brandon, 2026-11-17): held out of the people queue so the audit can read
// them. A hold ends after GRACE_DAYS or as soon as more of the person's books are on disk than when it was added
// (availableBooks in prefetch-books.js: full-length books in the local corpora), whichever comes first.
// Read by pending.js --people (so next.js and prefetch-books.js pass them over) and next.js's later-pass turns.
//   node scripts/waiting-for-books.js add <id> [<id> ...]   (whoever queues the download adds the entry)
//   node scripts/waiting-for-books.js sought <id> [<id> ...] (only records the search: nothing found to download; ends any hold)
//   node scripts/waiting-for-books.js hold <id> [<id> ...]   (holds people the maintainer is about to look for; not recorded
//                                                              as sought: Brandon, 2026-11-18, so the queue doesn't reach them first)
//   node scripts/waiting-for-books.js                        (lists each entry and whether it still holds)
// Every id given to add or sought is also kept in audits/books-sought.json, which never drops anyone (Brandon,
// 2026-11-18: "keep track of people who I tried to get as well so it isn't a large search going forward"). Holds end;
// that record doesn't, so a later search for books to look for can leave these people out.
// Books first (Brandon, 2026-11-18: "it's cheap to try, so error on the side of looking for books first"): a list of
// books to look for includes everyone with political books of their own, commentators too, even when columns or
// transcripts exist; order it by how much the books matter, never prune it.
const fs = require("fs");
const path = require("path");
const os = require("os");
const lib = require("./lib");
const FILE = path.join(lib.ROOT, "audits", "waiting-for-books.json");
const GRACE_DAYS = 14;
const today = () => new Date().toISOString().slice(0, 10);
const addDays = (d, n) => new Date(Date.parse(d) + n * 864e5).toISOString().slice(0, 10);
const read = () => (fs.existsSync(FILE) ? lib.readJson(FILE) : { people: [] });
const write = (data) => fs.writeFileSync(FILE, JSON.stringify({
  note: `Generated by scripts/waiting-for-books.js: people whose own books are being fetched, held out of the people queue for up to ${GRACE_DAYS} days, while the download queue still holds a download naming them (unfinished, or finished and not yet converted) (else until more of their books are on disk than when they were added).`,
  people: data.people }, null, 1) + "\n");

// The names of the downloads still in the download queue (a converted book's download is removed from it), or null when it can't be reached. A local helper outside the repo
// (corpora/tools/download-queue.sh) asks the downloader. One book arriving doesn't end a hold while others are still
// downloading (Brandon, 2026-11-19: Ann Coulter was audited when Resistance Is Futile landed, two more still queued).
function queuedDownloads() {
  const helper = path.join(os.homedir(), ".cache", "political-ideology-atlas", "corpora", "tools", "download-queue.sh");
  try { return require("child_process").execFileSync(helper, { encoding: "utf8", timeout: 20000 }).split("\n").filter(Boolean); }
  catch { return null; }
}

// Each entry with why it holds or not. A hold lasts GRACE_DAYS at most; within them it lasts while the download queue still
// holds a download naming the person, and when the queue can't be read, until more of their books are
// on disk than when they were added. Counting books on disk reads the corpora, so only listed people are counted.
function status() {
  const { people } = read();
  if (!people.length) return [];
  const prefetch = require("./prefetch-books");
  const catalog = new Map(lib.peopleCatalog().map((p) => [p.id, p]));
  const counts = prefetch.availableBooks(people.map((e) => catalog.get(e.id)).filter(Boolean));
  const downloads = queuedDownloads();
  return people.map((e) => {
    const until = addDays(e.since, GRACE_DAYS), books = counts[e.id] ?? 0;
    const p = catalog.get(e.id), match = p ? prefetch.nameMatcher(p) : () => false;
    const queued = downloads ? downloads.filter((n) => match(n)) : null;
    // A `hold` (on a books-to-look-for list, not yet looked for) lasts until add or sought, whatever the queue says
    // (Brandon, 2026-11-20: no audit before they are released or their downloads are queued).
    const why = today() >= until ? "grace period over"
      : e.searching ? null
      : queued ? (queued.length ? null : `nothing of theirs left downloading (${books} books on disk)`)
      : books > e.booksAtStart ? `books arrived (${e.booksAtStart} -> ${books}; download queue not readable)` : null;
    const holds = e.searching ? `held until ${until} or until looked for (add or sought)`
      : queued && queued.length ? `held until ${until} or their downloads finish (${queued.length} queued)`
      : `held until ${until} or more books on disk (download queue not readable)`;
    return { ...e, until, books, held: !why, why: why || holds };
  });
}
const held = () => new Set(status().filter((s) => s.held).map((s) => s.id));
// The permanent record of whose books have been looked for: id -> dates searched.
const SOUGHT = path.join(lib.ROOT, "audits", "books-sought.json");
const sought = () => (fs.existsSync(SOUGHT) ? lib.readJson(SOUGHT).people : {});
function recordSought(ids) {
  const people = sought();
  for (const id of ids) if (!(people[id] || []).includes(today())) people[id] = [...(people[id] || []), today()];
  fs.writeFileSync(SOUGHT, JSON.stringify({
    note: "Generated by scripts/waiting-for-books.js: people whose own books the maintainer has looked for, with the dates. Never pruned; searches for books to look for leave these people out.",
    people: Object.fromEntries(Object.entries(people).sort(([a], [b]) => a.localeCompare(b))) }, null, 1) + "\n");
}
module.exports = { held, status, sought };

if (require.main === module) {
  const [cmd, ...ids] = process.argv.slice(2);
  if (cmd === "add" || cmd === "sought" || cmd === "hold") {
    const catalog = new Map(lib.peopleCatalog().map((p) => [p.id, p]));
    const bad = ids.filter((id) => !catalog.has(id));
    if (!ids.length || bad.length) { console.error(`usage: add|sought <person id> ...${bad.length ? ` (not in the people catalog: ${bad.join(", ")})` : ""}`); process.exit(1); }
    if (cmd !== "hold") recordSought(ids);
  }
  if (cmd === "sought") write({ people: read().people.filter((e) => !ids.includes(e.id)) });
  if (cmd === "add" || cmd === "hold") {
    const catalog = new Map(lib.peopleCatalog().map((p) => [p.id, p]));
    // Entries that no longer hold are dropped as new ones are added.
    const keep = status().filter((s) => s.held && !ids.includes(s.id)).map(({ id, since, booksAtStart, searching }) => ({ id, since, booksAtStart, ...(searching ? { searching } : {}) }));
    const counts = require("./prefetch-books").availableBooks(ids.map((id) => catalog.get(id)));
    write({ people: [...keep, ...ids.map((id) => ({ id, since: today(), booksAtStart: counts[id] || 0, ...(cmd === "hold" ? { searching: true } : {}) }))] });
  }
  for (const s of status()) console.log(`${s.id}: since ${s.since}, ${s.books} books on disk (${s.booksAtStart} when added); ${s.why}`);
}
