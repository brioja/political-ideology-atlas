// People's other names for search (Brandon, 2026-11-14: "AOC" found no one). For every audited person, the
// redirects to their Wikipedia article that Wikipedia files as another name for them (short or long name,
// initialism, nickname, birth or former name, other spelling...), never a misspelling, an incorrect or
// non-neutral name, an eponym or a related word. Uncategorised redirects are left out: nothing says what they are.
// Wikidata aliases are not used (unreliable, found in an earlier check). Writes audits/people-aliases.json,
// read by scripts/build.js. Each person's requests are cached, so a rerun after new audits fetches only the new:
//   node scripts/people-aliases.js
"use strict";
const fs = require("fs");
const path = require("path");
const lib = require("./lib");

const OUT = path.join(lib.ROOT, "audits", "people-aliases.json");
// lib.cachedJson waits out a 429 itself.
const get = (params) => lib.cachedJson(`https://en.wikipedia.org/w/api.php?${new URLSearchParams({ format: "json", formatversion: "2", ...params })}`);
// Redirect categories ("Redirects from ...") that make a redirect another name for the person, and those that rule it out.
const NAME = /^Redirects (from (short|long|birth|alternative|former|maiden|married|personal|nick|pen|stage|religious|regnal|pseudonym|initialism|acronym|abbreviation|surname|alternative spelling|alternative transliteration|other capitalisation|alternative spacing|alternative punctuation|alternative hyphenation|diacritic|title without diacritics|ASCII|modification|names with title|other language|non-English|unnecessary disambiguation)|to initialism)/i;
const NOT = /^Redirects (from (misspelling|incorrect|miscapitalisation|non-neutral|eponym|related word|subtopic|member|sort name)|to (related topic|section|anchor|list))/i;
const linkTitle = (url) => decodeURIComponent(String(url || "").replace(/^https?:\/\/en\.wikipedia\.org\/wiki\//, "")).replace(/_/g, " ");

async function aliasesOf(title) {
  const redirects = [];
  let cont = {};
  do {
    const r = await get({ action: "query", titles: title, redirects: "1", prop: "redirects", rdprop: "title|fragment", rdnamespace: "0", rdlimit: "max", ...cont });
    for (const p of r.query.pages || []) for (const rd of p.redirects || []) if (!rd.fragment) redirects.push(rd.title);
    cont = r.continue || {};
  } while (cont.rdcontinue);
  const cats = new Map();
  for (let i = 0; i < redirects.length; i += 50) {
    cont = {};
    do {
      const r = await get({ action: "query", titles: redirects.slice(i, i + 50).join("|"), prop: "categories", cllimit: "max", ...cont });
      for (const p of r.query.pages || []) cats.set(p.title, [...(cats.get(p.title) || []), ...(p.categories || []).map((c) => c.title.replace(/^Category:/, ""))]);
      cont = r.continue || {};
    } while (cont.clcontinue);
  }
  return redirects.filter((t) => { const c = cats.get(t) || []; return c.some((k) => NAME.test(k)) && !c.some((k) => NOT.test(k)); });
}

// Saved as it goes, so a stop (a 429) keeps what was fetched.
function save(out) {
  const sorted = Object.fromEntries(Object.keys(out).sort().map((k) => [k, out[k]]));
  fs.writeFileSync(OUT, JSON.stringify({ note: "Generated by scripts/people-aliases.js from the English Wikipedia API: redirects to each audited person's article that Wikipedia files as another name for them. Read by scripts/build.js for search.", people: sorted }, null, 1) + "\n");
}

async function main() {
  const out = fs.existsSync(OUT) ? lib.readJson(OUT).people : {};
  const todo = lib.peopleCatalog().filter((e) => fs.existsSync(lib.personPath(e.id)) && linkTitle(e.wikipedia));
  let n = 0;
  for (const e of todo) {
    out[e.id] = await aliasesOf(linkTitle(e.wikipedia));
    if (++n % 50 === 0) { save(out); console.log(`${n} of ${todo.length}`); }
  }
  save(out);
  console.log(`${Object.keys(out).length} people, ${Object.values(out).flat().length} other names.`);
}
main().catch((e) => { console.error(e.message); process.exit(1); });
