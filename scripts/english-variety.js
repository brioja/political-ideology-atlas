// Which variety of English each entry's Wikipedia article uses (Brandon, 2026-11-06), read from its "Use ... English"
// template, so build.js can spell the entry's summary and role the same way (scripts/spelling.js). Articles
// without such a template are left out, and their text stays as written. Ideologies and people alike.
//   node scripts/english-variety.js        writes audits/english-variety.json
"use strict";
const fs = require("fs");
const path = require("path");
const lib = require("./lib");

const OUT = path.join(lib.ROOT, "audits", "english-variety.json");
// Template -> spelling: "us" (color, center, organize), "uk" (colour, centre, organise),
// "oxford" (colour, centre, organize: British with -ize).
const TEMPLATES = {
  "Use American English": "us", "Use Philippine English": "us",
  "Use British English": "uk", "Use Irish English": "uk", "Use Australian English": "uk", "Use New Zealand English": "uk",
  "Use Indian English": "uk", "Use Pakistani English": "uk", "Use Bangladeshi English": "uk", "Use Sri Lankan English": "uk",
  "Use South African English": "uk", "Use Nigerian English": "uk", "Use Ghanaian English": "uk", "Use Kenyan English": "uk",
  "Use Ugandan English": "uk", "Use Zimbabwean English": "uk", "Use Malaysian English": "uk", "Use Singapore English": "uk",
  "Use Hong Kong English": "uk", "Use Jamaican English": "uk", "Use Trinidad and Tobago English": "uk", "Use Scottish English": "uk",
  "Use Nepali English": "uk", "Use Maltese English": "uk",
  "Use British English Oxford spelling": "oxford", "Use Oxford spelling": "oxford", "Use Canadian English": "oxford",
};
const titleOf = (e) => decodeURIComponent(String(e.wikipedia || "").replace(/^https?:\/\/en\.wikipedia\.org\/wiki\//, "")).replace(/_/g, " ");

async function get(url) {
  for (let t = 0; ; t++) {
    try { return await lib.cachedJson(url, { pauseMs: 3000 }); }
    catch (e) { const m = e.message.match(/retry-after (\d+)/); if (!m || t >= 10) throw e; await new Promise((r) => setTimeout(r, (+m[1] + 10) * 1000)); }
  }
}

async function main() {
  const entries = [...lib.catalog().map((e) => ({ id: e.id, title: lib.articleTitle(e) })), ...lib.peopleCatalog().map((p) => ({ id: p.id, title: titleOf(p) }))]
    .filter((e) => e.title);
  const titles = [...new Set(entries.map((e) => e.title))];
  const tl = Object.keys(TEMPLATES).map((t) => "Template:" + t).join("|");
  const variety = new Map();
  for (let i = 0; i < titles.length; i += 50) {
    const batch = titles.slice(i, i + 50);
    let cont = {};
    do {
      const r = await get(`https://en.wikipedia.org/w/api.php?${new URLSearchParams({ action: "query", format: "json", formatversion: "2", redirects: "1",
        prop: "templates", tlnamespace: "10", tllimit: "max", tltemplates: tl, titles: batch.join("|"), ...cont })}`);
      const norm = new Map([...(r.query.normalized || []), ...(r.query.redirects || [])].map((x) => [x.to, x.from]));
      for (const p of r.query.pages || []) for (const t of p.templates || []) {
        const v = TEMPLATES[t.title.replace(/^Template:/, "")];
        if (!v) continue;
        let k = p.title; variety.set(k, v); for (let j = 0; j < 3 && norm.has(k); j++) { k = norm.get(k); variety.set(k, v); }
      }
      cont = r.continue || {};
    } while (cont.tlcontinue);
  }
  const out = {};
  for (const e of entries) if (variety.has(e.title)) out[e.id] = variety.get(e.title);
  fs.writeFileSync(OUT, JSON.stringify({ note: "Generated by scripts/english-variety.js: the English variety each entry's Wikipedia article declares (us, uk, oxford); build.js spells summaries and roles to match. Entries without a declared variety are absent and keep their spelling.", fetched: new Date().toISOString().slice(0, 10), entries: out }, null, 1) + "\n");
  const n = Object.values(out);
  console.log(`${entries.length} entries: ${n.length} declare a variety (us ${n.filter((v) => v === "us").length}, uk ${n.filter((v) => v === "uk").length}, oxford ${n.filter((v) => v === "oxford").length}); the rest stay as written.`);
}
main().catch((e) => { console.error(e.message); process.exit(1); });
