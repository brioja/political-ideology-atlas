// Explanation review loop (Brandon, 2026-11-15): "What does this mean?" shows each statement's agree and disagree
// sentences, and a quiz taker found they only restated the statement. This walks the active statements in quiz
// order and writes a review brief for the first one whose agree or disagree sentence restates it
// (statements-check.js --explanations) and has no review yet. A reviewer (Codex, following
// audits/PROMPT_EXPLANATION_REVIEW.md) answers in scratchpad/explanation-review/<id>-results.md; nothing here edits
// statements.json, and the integrator applies the accepted proposals (agree/disagree texts are the integrator's call).
//   node scripts/explanation-review.js next   write the next brief, print its path (or "none")
//   node scripts/explanation-review.js list   print the queue in quiz order, reviewed ones marked
//   --id <id>: write the brief for that statement, reviewed or not
const fs = require("fs");
const path = require("path");
const { ROOT, allStatements, isCandidate, quizOrder, answersTo, restateSimilarity, RESTATE_LIMITS } = require("./lib");

const OUT = path.join(ROOT, "scratchpad", "explanation-review");
const idArg = process.argv.indexOf("--id");
const ONE = idArg > -1 ? process.argv[idArg + 1] : null;
const mode = process.argv[2];

const byId = new Map(allStatements().map((s) => [s.id, s]));
const restating = (s, k) => !!s[k] && restateSimilarity(s.text, s[k]) >= RESTATE_LIMITS[k];
const flagged = (s) => restating(s, "agree") || restating(s, "disagree");
const resultsFile = (id) => path.join(OUT, `${id}-results.md`);

// The **Agree:** and **Disagree:** lines a review proposes; a review counts once neither still restates, or it
// keeps the current texts on purpose (**Verdict:** keep).
function proposal(id) {
  if (!fs.existsSync(resultsFile(id))) return null;
  const t = fs.readFileSync(resultsFile(id), "utf8");
  const line = (k) => { const m = t.match(new RegExp(`^\\*\\*${k}:\\*\\*\\s*(.+?)\\s*$`, "mi")); return m ? m[1].replace(/^["“]|["”]$/g, "") : null; };
  return { verdict: line("Verdict"), agree: line("Agree"), disagree: line("Disagree") };
}
function reviewed(s) {
  const p = proposal(s.id);
  if (!p) return false;
  if (p.verdict && /^keep\b/i.test(p.verdict)) return true;
  return ["agree", "disagree"].every((k) => !restating({ text: s.text, [k]: p[k] || s[k] }, k));
}

function queue() {
  return quizOrder().map((id, i) => ({ step: i + 1, s: byId.get(id) })).filter((x) => x.s && !isCandidate(x.s) && flagged(x.s));
}

const clip = (t, n = 260) => (t.length > n ? t.slice(0, n - 1).trimEnd() + "…" : t);
// A few rationales per answer value, spread over the list, so the reviewer sees the different reasons subjects
// give for one side: an explanation must be true of all of them.
const spreadOver = (list, n) => list.filter((_, i) => i % Math.max(1, Math.floor(list.length / n)) === 0).slice(0, n);

function brief(step, s) {
  const ans = answersTo(s.id), count = {};
  for (const a of ans) count[a.value] = (count[a.value] || 0) + 1;
  const entry = Object.fromEntries(["id", "text", "agree", "disagree", "note"].filter((k) => s[k] !== undefined).map((k) => [k, s[k]]));
  const side = (label, values) => {
    const list = ans.filter((a) => values.includes(a.value));
    return `**${label}** (${list.length}):\n\n${spreadOver(list, 6).map((a) => `- \`${a.who}\` (${a.value > 0 ? "+" : ""}${a.value}): "${clip(a.rationale)}"`).join("\n") || "_None._"}`;
  };
  const sim = (k) => (s[k] ? `${Math.round(restateSimilarity(s.text, s[k]) * 100)}%${restating(s, k) ? " (restates)" : ""}` : "none");
  const earlier = proposal(s.id);
  return `# Explanations for \`${s.id}\`

Explanation review, generated by \`node scripts/explanation-review.js\` on ${new Date().toISOString().slice(0, 10)}. Follow
\`audits/PROMPT_EXPLANATION_REVIEW.md\`.

## The task

A quiz taker who taps "What does this mean?" sees the statement, then "If you agree" and "If you disagree". Here
at least one of those only repeats the statement, so it explains nothing. Propose an \`agree\` and a \`disagree\`
sentence that help a reader see each position, without changing what the statement asks. The statement text
and the note stay as they are.

Write your reply to \`scratchpad/explanation-review/${s.id}-results.md\` (a new file; touch nothing else), with:

1. **Verdict:** reword, or keep (when no faithful rewording exists; say why).
2. **Agree:** the sentence, on one line.
3. **Disagree:** the sentence, on one line.
4. For each side, which audited subjects you checked it against and why it holds for all of them.
5. A one-line verdict on any alternative you considered.

## The statement now (quiz step ${step})

\`\`\`json
${JSON.stringify(entry, null, 1)}
\`\`\`

Words shared with the statement (\`node scripts/statements-check.js --explanations\`): agree ${sim("agree")}, disagree
${sim("disagree")}. Limits: agree under ${Math.round(RESTATE_LIMITS.agree * 100)}%, disagree under ${Math.round(RESTATE_LIMITS.disagree * 100)}%.

${earlier ? `**An earlier review's proposal still restates the statement** (agree "${earlier.agree || "-"}", disagree "${earlier.disagree || "-"}"). Propose texts that pass, or give **Verdict:** keep with a reason, and overwrite \`${s.id}-results.md\`.\n\n` : ""}## Who answers each way

${ans.length} answers: ${[-2, -1, 0, 1, 2].map((v) => `${v > 0 ? "+" : ""}${v}: ${count[v] || 0}`).join(", ")}. Each sentence must be true of
everyone on its side, whatever their reason; read the full set in the audit files.

${side("Agree", [1, 2])}

${side("Disagree", [-1, -2])}

## Rules (STANDARD.md "Explanations")

- **Agree** means exactly the statement, in other words that help a reader see the position: plainer words, what
  it would look like in practice, an example. It adds no claim the statement lacks, and no reason.
- **Disagree** is a clean positive opposite where one exists and means exactly "not the statement" ("Military
  service should always be voluntary"); otherwise the plain negation, and then rewording the agree side is
  the whole fix. Not the opposite extreme: a subject answering -1 must fit it too. Never an either/or.
  For "more A than B" keep both sides ("at least as much B as A").
- Both are true of every subject who answers that way, whatever their reason (check the rationales above).
- Plain, neutral words both sides would accept as fair. One sentence each.
- Check: \`node scripts/statements-check.js --explanations\` scores the current texts; to score yours, run
  \`node -e 'const {restateSimilarity}=require("./scripts/lib");console.log(restateSimilarity(process.argv[1],process.argv[2]))' "<statement>" "<your sentence>"\`.

## Files

- \`statements.json\`: the entry. \`audits/statements/STANDARD.md\`: the standard.
- Rationales: \`answers["${s.id}"]\` in \`audits/profiles/*.json\` and \`audits/people/*.json\`.
`;
}

function write(step, s) {
  fs.mkdirSync(OUT, { recursive: true });
  const f = path.join(OUT, `${s.id}-brief.md`);
  fs.writeFileSync(f, brief(step, s));
  console.log(path.relative(ROOT, f));
}

if (ONE) {
  const s = byId.get(ONE);
  if (!s) { console.error(`no statement ${ONE}`); process.exit(1); }
  write(quizOrder().indexOf(ONE) + 1 || "-", s);
} else if (mode === "list") {
  const q = queue();
  const state = (s) => (reviewed(s) ? "reviewed" : fs.existsSync(resultsFile(s.id)) ? "redo    " : "pending ");
  for (const { step, s } of q) console.log(`${String(step).padStart(3)} ${state(s)} ${s.id}: ${s.text}`);
  console.log(`\n${q.length} active statements have an agree or disagree sentence that restates them; ${q.filter((x) => reviewed(x.s)).length} reviewed.`);
} else if (mode === "next") {
  const next = queue().find((x) => !reviewed(x.s));
  if (!next) { console.log("none"); process.exit(0); }
  write(next.step, next.s);
} else {
  console.log("usage: node scripts/explanation-review.js next|list | --id <id>");
}
